import os
import sys

# Make imports resolve whether this script is run from the repo root or
# from inside scripts/.
_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO_ROOT = os.path.dirname(_HERE)
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

import imageio.v2 as imageio
import matplotlib.pyplot as plt
import numpy as np
from omegaconf import OmegaConf

from gavis import GAVIS
from gavis.data_utils import load_dataset_from_transforms_json
from gavis.render_utils import (
    aabb_from_depths,
    load_depths,
    load_eval_poses,
    render_trajectory_rgb,
    save_gif,
)
from gavis.train_utils import train_gaussian_model
from scripts.scene_pipeline import load_scene_ckpt, save_scene_ckpt


DATA_NAME = "Barboursville"
DATA_DIR = os.path.join(_REPO_ROOT, f"data/{DATA_NAME}/partial")
JSON_PATH = os.path.join(DATA_DIR, "transforms.json")
EVAL_JSON = os.path.join(DATA_DIR, "eval.json")
OUT_DIR = os.path.join(_REPO_ROOT, "outputs")
MODEL_PATH = os.path.join(OUT_DIR, f"{DATA_NAME}.pth")
RGB_GIF = os.path.join(OUT_DIR, "rgb_pred.gif")
UQ_GIF = os.path.join(OUT_DIR, "uq.gif")

# 10% margin gives the visibility-field construction and UQ rendering some
# headroom around the depth-observed scene bounds.
AABB_MARGIN = 0.1


def main():
    os.makedirs(OUT_DIR, exist_ok=True)

    # 1. Train (or reuse a cached checkpoint). The ckpt carries the
    # trained gaussians along with the training poses, intrinsics, and
    # depth-derived AABB so subsequent runs skip straight to rendering.
    if os.path.isfile(MODEL_PATH):
        model, meta = load_scene_ckpt(MODEL_PATH, device="cuda")
        poses = meta["training_poses"]
        H, W = meta["H"], meta["W"]
        fovx, fovy = meta["fovx"], meta["fovy"]
        aabb = meta["aabb"]
        print(
            f"[example] loaded cached model from {MODEL_PATH}: "
            f"{model.get_xyz.shape[0]} gaussians, {len(poses)} training poses"
        )
    else:
        # Load images + COLMAP poses + intrinsics, and the depth maps.
        images, poses, fovx, fovy, H, W, alpha_masks = load_dataset_from_transforms_json(
            JSON_PATH,
            white_background=True,
            pose_convention="colmap",
            return_alpha_masks=True,
        )
        depths = load_depths(JSON_PATH)
        print(
            f"[example] loaded {len(images)} views H={H} W={W} "
            f"fovx={fovx:.4f} fovy={fovy:.4f} ({len(depths)} depth maps)"
        )

        # Estimate the scene AABB straight from the depth point cloud,
        # padded by AABB_MARGIN so the visibility field has a bit of
        # headroom around the observed bounds.
        aabb = aabb_from_depths(
            poses, depths, fovx, fovy, H, W, margin=AABB_MARGIN
        )

        # Train 3DGS (depth init) and persist the ckpt for reuse.
        model = train_gaussian_model(
            images=images,
            poses=poses,
            fovx=fovx,
            fovy=fovy,
            H=H,
            W=W,
            aabb=aabb.tolist(),
            alpha_masks=alpha_masks,
            depths=depths,
            use_depth_init=True,
            use_depth_supervision=False,
            iterations=7500,
            sh_degree=3,
            white_background=True,
            random_background=False,
        )
        save_scene_ckpt(
            gaussians=model,
            ckpt_path=MODEL_PATH,
            training_poses=poses,
            H=H,
            W=W,
            fovx=fovx,
            fovy=fovy,
            aabb=aabb,
        )
        print(
            f"[example] trained 3DGS: {model.get_xyz.shape[0]} gaussians "
            f"(saved to {MODEL_PATH})"
        )

    # 2. Load the eval-set trajectory (generated by
    # scripts/gen_eval_barboursville.py from the slide-trajectory in
    # gen_gifs.py:main()).
    eval_poses = load_eval_poses(EVAL_JSON)
    print(f"[example] loaded {len(eval_poses)} eval poses from {EVAL_JSON}")

    # 3. Render the trained model's RGB along the eval poses.
    rgb_frames = render_trajectory_rgb(
        model=model,
        trajectory=eval_poses,
        H=H,
        W=W,
        fovx=fovx,
        fovy=fovy,
        white_background=True,
    )
    save_gif(rgb_frames, RGB_GIF, duration=0.1)
    print(f"[example] wrote {RGB_GIF}")

    # 4. Visibility-guided uncertainty along the eval poses. GAVIS
    # preprocessing still consumes the *training* poses — the eval poses
    # are only used as query views for render_uncertainty_map.
    cfg = OmegaConf.create(
        {
            "H": int(H),
            "W": int(W),
            "fovx": float(fovx),
            "fovy": float(fovy),
            "aabb": np.asarray(aabb).tolist(),
        }
    )
    gavis = GAVIS(cfg)
    gavis.load_model(model, poses)
    print(
        f"[example] GAVIS preprocessing done: "
        f"{gavis.model.get_xyz.shape[0]} gaussians total "
        f"({gavis._visibility_handler.num_fixed_gaussians} fixed)"
    )

    raws = np.stack(
        [gavis.render_uncertainty_map(pose).numpy() for pose in eval_poses],
        axis=0,
    )
    lo, hi = float(raws.min()), float(raws.max())

    # Min/max scaling is only the viridis display mapping for the gif (the
    # scene geometry itself is left un-normalized).
    uq_frames = [
        (plt.cm.viridis((u - lo) / (hi - lo + 1e-8))[:, :, :3] * 255).astype(np.uint8)
        for u in raws
    ]
    imageio.mimsave(UQ_GIF, uq_frames, duration=0.1, loop=0)
    print(f"[example] wrote {UQ_GIF}")


if __name__ == "__main__":
    main()
